// Builds js/carRoster.js from the 100-car asset pack. Keeps only the fields the
// simulation and the car-select UI actually read, so the module stays small
// enough to ship unbundled.
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2];
if (!src || !fs.existsSync(src)) {
  console.error('usage: node tools/gen-roster.mjs <path to cars.json>');
  process.exit(1);
}
const db = JSON.parse(fs.readFileSync(src, 'utf8'));

// Road-car tiers map onto two driving classes: everything up to a tuned street
// car shares one envelope, everything from a supercar upward shares another.
const CLASS_FOR_TIER = { base: 'street', tuned: 'street', super: 'hyper', hyper: 'hyper' };

const cars = db.cars.map((c) => ({
  id: c.id,
  name: c.name,
  make: c.manufacturer,
  model: c.model,
  year: c.year,
  tier: c.tier,
  vehicleClass: CLASS_FOR_TIER[c.tier] || 'street',
  body: c.body_type,
  colour: c.visual?.primary_color || '#c8ccd2',
  accent: c.visual?.accent_color || '#20242a',
  engine: c.engine?.label || '',
  soundFamily: c.engine?.sound_family || 'v8',
  idleRpm: c.engine?.idle_rpm ?? 900,
  redlineRpm: c.engine?.redline_rpm ?? 7000,
  performance: {
    power_hp: c.performance.power_hp,
    torque_nm: c.performance.torque_nm,
    weight_kg: c.performance.weight_kg,
    drivetrain: c.performance.drivetrain,
    top_speed_kmh: c.performance.top_speed_kmh,
    accel_0_100_kmh_s: c.performance.accel_0_100_kmh_s,
    performance_index: c.performance.performance_index,
    performance_class: c.performance.performance_class,
  },
  drivetrain_detail: { gears: c.drivetrain_detail?.gears ?? 6 },
  price: c.economy?.price_credits ?? 0,
  unlock: c.economy?.unlock_level ?? 1,
  blurb: c.blurb || '',
}));

const out = `// GENERATED by tools/gen-roster.mjs — do not edit by hand.
// Source: the 100-car asset pack (original fictional marques, no real-world
// trademarks). Regenerate with:
//   node tools/gen-roster.mjs <path>/fictional-car-pack/cars.json
//
// \`vehicleClass\` selects the physics profile in js/vehicleClasses.js; the rest
// feeds car select, liveries and engine audio.
export const CAR_ROSTER = ${JSON.stringify(cars, null, 1)};

export const ROSTER_BY_ID = Object.freeze(Object.fromEntries(
  CAR_ROSTER.map((car) => [car.id, car])));

export function carsForTier(...tiers) {
  return CAR_ROSTER.filter((car) => tiers.includes(car.tier));
}
export function carsForClass(vehicleClass) {
  return CAR_ROSTER.filter((car) => car.vehicleClass === vehicleClass);
}
// Cars within a performance-index window — used to build a competitive grid.
export function gridFor(car, size = 12, tolerance = 60) {
  const target = car.performance.performance_index;
  return CAR_ROSTER
    .filter((c) => c.vehicleClass === car.vehicleClass && c.id !== car.id)
    .map((c) => ({ c, d: Math.abs(c.performance.performance_index - target) }))
    .filter((e) => e.d <= tolerance)
    .sort((a, b) => a.d - b.d)
    .slice(0, size - 1)
    .map((e) => e.c);
}
`;
fs.writeFileSync(path.join(process.cwd(), 'js/carRoster.js'), out);
const byClass = cars.reduce((m, c) => (m[c.vehicleClass] = (m[c.vehicleClass] || 0) + 1, m), {});
console.log(`js/carRoster.js written: ${cars.length} cars`, byClass,
  `${(out.length / 1024).toFixed(0)} KB`);
